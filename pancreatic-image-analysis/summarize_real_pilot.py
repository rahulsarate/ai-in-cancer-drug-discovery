"""Create a concise audit report and expert-review template from the pilot run."""
from pathlib import Path
import csv
import json

ROOT=Path(__file__).resolve().parent; OUT=ROOT/'outputs/real_pilot'
r=json.loads((OUT/'pilot_results.json').read_text()); p=r['primary_endpoints']; e=r['exploratory_emt']
g=r['technical_gates']
technical=all(g[k] for k in ['all_raw_files_verified','at_least_22_evaluable_patients','all_patients_have_at_least_8_tiles']) and g['cross_patient_exact_tile_duplicates']==0
direction='did not improve on' if e['model_mae']>=e['baseline_mae'] else 'had lower point-estimate error than'
lines=[
    '# TCGA-PAAD real-data technical pilot: measured results',
    '',
    'Research only. This report supersedes synthetic demonstration metrics for the real-data pilot; it is not a clinical performance report.',
    '',
    '## Technical completion',
    f"- Selected / evaluable patients: {p['selected_patients']} / {p['evaluable_patients']}.",
    f"- Verified source files: {p['verified_raw_files']}; source data: {p['verified_raw_bytes']/1e9:.3f} GB.",
    f"- Retained tissue tiles: {p['retained_tiles']}; processing exclusions: {len(p['exclusions'])}.",
    f"- Prespecified technical completion gates: {'PASS' if technical else 'FAIL'}.",
    '- Expert tumor review and same-block image/RNA correspondence: not established.',
    '',
    '## Cohort composition',
    f"- Exact pathological stages: {r['stage_counts_exact']}.",
    f"- Staging editions: {r['staging_editions']}.",
    f"- Tissue-source-site groups: {r['sites']}.",
    '- Convenience selection by slide file size, not representative or outcome-powered.',
    '',
    '## Exploratory biological association',
    f"- Image Ridge MAE: {e['model_mae']:.4f}; training-mean baseline MAE: {e['baseline_mae']:.4f} score units.",
    f"- Descriptive model-MAE 95% interval: {e['model_mae_percentile_95']}.",
    f"- Baseline-minus-model MAE improvement: {e['mae_improvement_over_baseline']:.4f}; descriptive interval: {e['mae_improvement_over_mean_percentile_95']}.",
    f"- RMSE: {e['model_rmse']:.4f}; R-squared: {e['model_r2']:.4f}; Spearman r: {e['spearman_r']:.4f}.",
    f'- The image model {direction} the training-mean baseline.',
    '- The descriptive improvement interval includes zero; predictive advantage is not established.' if e['mae_improvement_over_mean_percentile_95'][0]<=0<=e['mae_improvement_over_mean_percentile_95'][1] else '- Interpret the error difference with the stated small-sample and bootstrap limitations.',
    '- Leave-one-source-site-out evaluation within TCGA only. Bootstrap intervals are conditional on fixed predictions and omit site clustering and model refitting.',
    '- The target is a prespecified, unbounded bulk RNA expression contrast, not a validated EMT assay. Stromal confounding and block mismatch remain.',
    '',
    '## Stage and clinical conclusions',
    f"- Four-stage model: {r['stage_model']['status']}. {r['stage_model']['reason']}.",
    '- No diagnosis, full stage, EMT progression, treatment response or patient-specific therapeutic recommendation is established.',
    '- Technical success supports expert review and a redesigned, larger validation study, not clinical deployment.',
    '',
    '## Reproduction and review',
    'Run `python acquire_pilot.py`, `python run_real_pilot.py`, and `python summarize_real_pilot.py` from the project folder after installing requirements-pilot.txt.',
    'Review pilot_results.json, patient_manifest.csv, tile_manifest.csv, signature_tpm.csv, patient_features.csv and out_of_fold_predictions.csv.',
    'Expert review fields in expert_review_template.csv are intentionally blank. No review has been fabricated.',
    '',
    'Results are based on data generated by the TCGA Research Network: https://www.cancer.gov/tcga.',
    'See docs/PILOT_PROTOCOL.md and docs/PILOT_REPORTING_CHECKLIST.md for eligibility, limitations, source references and outstanding work.'
]
(OUT/'PILOT_REPORT.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
review_path=OUT/'expert_review_template.csv'
if not review_path.exists():
    with (OUT/'tile_manifest.csv').open(encoding='utf-8') as f: tiles=list(csv.DictReader(f))
    with review_path.open('w',newline='',encoding='utf-8') as f:
        fields=['patient_id','tile_path','reviewer_id','review_date','adequate_yes_no','tumor_fraction_0_1','stroma_fraction_0_1','artifact_notes','include_for_tumor_study_yes_no']
        w=csv.DictWriter(f,fieldnames=fields); w.writeheader()
        for t in tiles: w.writerow({'patient_id':t['patient_id'],'tile_path':t['tile_path']})
print(OUT/'PILOT_REPORT.md')
